# 复刻 matchPoemGrade 解析结果（作为已标注诗的年级）
map_m = re.search(open(f"{ROOT}/site/app.js", encoding="utf-8").read().find if False else r'const POEM_GRADE_MAP = (\[[\s\S]*?\]);', open(f"{ROOT}/site/app.js", encoding="utf-8").read())
POEM_GRADE_MAP = eval(map_m.group(1))

def match_grade(title):
    parts = re.split(r'[（(·\-—]', str(title or ""))
    base = parts[0].replace(" ", "").replace("　", "")
    alt = re.sub(r'[）)\s]', "", parts[1] if len(parts) > 1 else "")
    cands = [e for e in POEM_GRADE_MAP if e[0] == base]
    if not cands: return None
    if len(cands) == 1: return cands[0][1]
    pick = next((e for e in cands if len(e) > 2 and e[2] and e[2] in alt), None)
    return (pick or cands[0])[1]

filled, kept, missing = 0, 0, []
for p in D["poems"]:
    t = p["title"]
    if t in NULL_GRADES:
        p["grade"] = NULL_GRADES[t]; filled += 1
    else:
        g = match_grade(t)
        if g:
            p["grade"] = g; kept += 1
        else:
            missing.append(t)

# 重新序列化：grade 插到 title 之后，保持紧凑单行
def order_poem(p):
    out = {}
    for k, v in p.items():
        out[k] = v
        if k == "title" and "grade" in p:
            out["grade"] = p["grade"]
    return out
D["poems"] = [order_poem(p) for p in D["poems"]]

out = "window.STUDY_DATA = " + json.dumps(D, ensure_ascii=False, separators=(",", ":")) + ";\n"
open(SRC, "w", encoding="utf-8").write(out)

